const router = require('express').Router();
const c = require('../controllers/teamController');
const { requireAuth, requireRole } = require('../middleware/auth.middleware');
router.get('/widgets/publicos', c.publicWidgets);
router.use(requireAuth);
router.use((_req,res,next) => { res.set('Cache-Control','no-store'); next(); });
const editor = requireRole('admin','editor');
const support = requireRole('admin','soporte');
const reception = requireRole('admin','registrador');
router.get('/widgets',editor,c.widgets);
router.post('/widgets',editor,c.saveWidget);
router.put('/widgets/:id',editor,c.saveWidget);
router.delete('/widgets/:id',editor,c.deleteWidget);
router.get('/soporte',requireRole('admin','soporte','cliente'),c.cases);
router.post('/soporte',requireRole('cliente'),c.createCase);
router.get('/soporte/:id',requireRole('admin','soporte','cliente'),c.caseDetail);
router.post('/soporte/:id/mensajes',requireRole('admin','soporte','cliente'),c.message);
router.patch('/soporte/:id',support,c.updateCase);
router.get('/clientes',reception,c.customers);
router.post('/clientes',reception,c.createCustomer);
router.get('/caja',reception,c.shift);
router.post('/caja',reception,c.openShift);
router.post('/caja/:id/cierre',reception,c.closeShift);
router.post('/ventas',reception,c.sell);
module.exports = router;
